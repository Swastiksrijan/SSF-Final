export function t(key, lang = 'en') {
  const e = DICT[key];
  if (!e) return key;
  return e[lang] || e.en || key;
}

/** Both languages for a key, so labels can be shown bilingually at once. */
export function tBoth(key) {
  const e = DICT[key];
  if (!e) return [key, key];
  return [e.en, e.hi || e.en];
}
